const dictionaries: Record<Language, Record<string, string>> = { zh, en };

export function currentLanguage(): Language {
  try {
    return localStorage.getItem(LANG_KEY) === "en" ? "en" : "zh";
  } catch {
    return "zh";
  }
}

export function setLanguage(language: Language): void {
  try { localStorage.setItem(LANG_KEY, language); } catch { /* non-browser environments */ }
}

export function t(key: string): string {
  const dictionary = dictionaries[currentLanguage()];
  return dictionary[key] ?? dictionaries.en[key] ?? key;
}

export function tf(key: string, params: Record<string, string | number>): string {
  let value = t(key);
  for (const [name, replacement] of Object.entries(params)) {
    value = value.split(`{${name}}`).join(String(replacement));
  }
  return value;
}
